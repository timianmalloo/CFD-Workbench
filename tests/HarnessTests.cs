using System.Diagnostics;
using System.Reflection;
using System.Runtime.CompilerServices;
using Microsoft.Testing.Platform.Builder;
using Xunit;

namespace CfdWorkbench.Tests;

/// <summary>
/// The entry point every test project shares (its Program.cs calls this). `--harness …` runs the project's console harness in
/// this process: what <see cref="HarnessRun"/> spawns, what the Desktop harness's SelfLaunch passes to each child, and what a
/// tool calls for a mode (`--harness --write-stl-fixtures <dir>`, `--harness --readiness`). Anything else is xunit: the
/// Microsoft.Testing.Platform server that `dotnet test` starts, or the in-process console runner for `dotnet run`. The two xunit
/// branches are the body of the entry point xunit would otherwise generate (XunitAutoGeneratedEntryPoint is off in
/// tests/Directory.Build.props).
/// </summary>
public static class HarnessEntry
{
    public static async Task<int> Run(string[] args, Func<string[], Task<int>> harness, Action<ITestApplicationBuilder, string[]> extensions)
    {
        if (args is ["--harness", .. var rest]) return await harness(rest);
        if (args.Any(arg => arg is "--server" or "--internal-msbuild-node"))
            return await Xunit.MicrosoftTestingPlatform.TestPlatformTestFramework.RunAsync(args, extensions);
        return await Xunit.Runner.InProc.SystemConsole.ConsoleRunner.Run(args);
    }
}

/// <summary>One check line of a harness run: <c>PASS name</c>, <c>FAIL name detail</c> or <c>SKIP name reason</c>.</summary>
public sealed record CheckLine(string Name, string Verdict, string Detail);

/// <summary>What one harness run printed, how it exited and how long it took.</summary>
public sealed record HarnessResult(IReadOnlyList<CheckLine> Lines, int ExitCode, TimeSpan Elapsed, string Log);

/// <summary>
/// Runs this project's harness once per test process, as a child (`<assembly> --harness`: the apphost beside the test
/// assembly), from the checked-out tree's root. The root is needed because the harnesses read `docs/examples/…` and
/// `src/…/Assets/example.foil` relative to the current directory while `dotnet test` starts the test process in the build output
/// directory; it comes from this file's compile-time path (CallerFilePath, the one sanctioned way: SelfLaunch.cs's
/// NoRuntimeRepoRootWalk), never a runtime walk. A child process rather than an in-process call because the Desktop harness spawns
/// itself per suite and sets up one Avalonia application per process, and because the harnesses' checks share fixtures in
/// registration order, which a test framework's own ordering would not keep.
/// </summary>
public static class HarnessRun
{
    private static readonly Lazy<HarnessResult> run = new(Execute);

    public static HarnessResult Result => run.Value;

    private static HarnessResult Execute()
    {
        string name = Assembly.GetExecutingAssembly().GetName().Name!;
        string host = Path.Combine(AppContext.BaseDirectory, name + (OperatingSystem.IsWindows() ? ".exe" : ""));
        var info = new ProcessStartInfo(host)
        {
            UseShellExecute = false, RedirectStandardOutput = true, RedirectStandardError = true, WorkingDirectory = RepositoryRoot(),
        };
        info.ArgumentList.Add("--harness");
        long started = Stopwatch.GetTimestamp();
        using var process = Process.Start(info) ?? throw new InvalidOperationException("could not start " + host);
        Task<string> output = process.StandardOutput.ReadToEndAsync();
        Task<string> error = process.StandardError.ReadToEndAsync();
        process.WaitForExit();
        var lines = new List<CheckLine>();
        foreach (string raw in output.Result.Split('\n'))
        {
            string[] parts = raw.TrimEnd('\r').Split(' ', 3);
            if (parts.Length >= 2 && parts[0] is "PASS" or "FAIL" or "SKIP")
                lines.Add(new CheckLine(parts[1], parts[0], parts.Length == 3 ? parts[2] : ""));
        }
        return new HarnessResult(lines, process.ExitCode, Stopwatch.GetElapsedTime(started), output.Result + error.Result);
    }

    private static string RepositoryRoot([CallerFilePath] string self = "") =>
        Path.GetFullPath(Path.Combine(Path.GetDirectoryName(self)!, ".."));
}

/// <summary>Each harness check as one test, plus the harness's own verdict: its exit code, and that it printed checks at all.</summary>
public class HarnessTests
{
    public static IEnumerable<object[]> Checks() =>
        HarnessRun.Result.Lines.Select(line => line.Name).Distinct(StringComparer.Ordinal).Select(name => new object[] { name });

    [Theory]
    [MemberData(nameof(Checks))]
    public void Check(string name)
    {
        // A name printed more than once (a check registered in a loop) reports its worst line: FAIL, else PASS, else SKIP.
        List<CheckLine> lines = HarnessRun.Result.Lines.Where(line => line.Name == name).ToList();
        CheckLine worst = lines.FirstOrDefault(line => line.Verdict == "FAIL") ?? lines.FirstOrDefault(line => line.Verdict == "PASS") ?? lines[0];
        Assert.SkipWhen(worst.Verdict == "SKIP", worst.Detail);
        Assert.True(worst.Verdict == "PASS", worst.Detail);
    }

    /// <summary>
    /// An exit code is not a result, and a result needs checks: a harness that exits 0 without one PASS line fails
    /// (HARNESS-SILENT-EXIT). A name printed twice is two checks sharing one name, so one could mask the other's result and the
    /// test list above would show one test for two: that fails too (TEST-NAME-DUPLICATE).
    /// </summary>
    [Fact]
    public void Harness_ExitsZero_AfterPrintingChecks()
    {
        HarnessResult result = HarnessRun.Result;
        string summary = $"exit {result.ExitCode} after {result.Elapsed.TotalSeconds:F0} s; " +
            $"{result.Lines.Count(line => line.Verdict == "PASS")} PASS, {result.Lines.Count(line => line.Verdict == "FAIL")} FAIL, " +
            $"{result.Lines.Count(line => line.Verdict == "SKIP")} SKIP";
        string[] log = result.Log.Split('\n');
        Assert.True(result.ExitCode == 0 && result.Lines.Any(line => line.Verdict == "PASS"),
            summary + "\n" + string.Join('\n', log.Skip(Math.Max(0, log.Length - 40))));
        List<string> duplicates = result.Lines.GroupBy(line => line.Name, StringComparer.Ordinal).Where(group => group.Count() > 1).Select(group => group.Key).ToList();
        Assert.True(duplicates.Count == 0, "a check name printed more than once: " + string.Join(", ", duplicates));
    }
}
